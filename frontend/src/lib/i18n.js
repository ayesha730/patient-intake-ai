// Returns the text for a language, falling back to English if a key is missing
export function tr(lang, key) {
  const table = STRINGS[lang] || STRINGS.en;
  return table[key] !== undefined ? table[key] : STRINGS.en[key];
}

export function dirOf(lang) {
  const found = LANGUAGES.find((l) => l.code === lang);
  return found ? found.dir : "ltr";
}